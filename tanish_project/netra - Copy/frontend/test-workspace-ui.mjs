import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
import {mkdir,readFile} from 'node:fs/promises'
await mkdir('../../test-results',{recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
const nav=name=>page.getByRole('button',{name,exact:true}).click()
try {
 await page.goto('http://127.0.0.1:8001')
 await nav('Workspace guide')
 await page.getByRole('heading',{name:'Your audience walkthrough'}).waitFor()
 await nav('Accuracy lab');await nav('Run controlled evaluation')
 await page.getByText('18 / 18 expected outcomes matched').waitFor()
 await page.screenshot({path:'../../test-results/accuracy-lab.png',fullPage:true,animations:'disabled'})
 await nav('Website checkup');await page.getByRole('button',{name:'Show me an example'}).click()
 await page.getByText('EXAMPLE DATA · FICTIONAL WEBSITE').waitFor()
 await nav('Public information');await page.getByText('Example registrar (fictional)',{exact:true}).waitFor()
 await nav('Google search assistant');await page.getByLabel('Search scope',{exact:true}).selectOption('website');await nav('Generate search queries')
 await page.getByRole('heading',{name:'Public documents',exact:true}).waitFor()
 assert.equal(await page.getByRole('button',{name:'Copy query',exact:true}).count(),13)
 assert.equal(await page.getByRole('link',{name:'Open Google'}).count(),0)
 await page.getByLabel('Title',{exact:true}).fill('Example public report')
 await page.getByLabel('Source URL',{exact:true}).fill('https://example.com/report.pdf')
 await page.getByLabel('Notes',{exact:true}).fill('Review whether publication is intentional.')
 await nav('Save research lead')
 await page.getByRole('heading',{name:'Example public report',exact:true}).waitFor()
 await nav('Edit lead');await page.getByLabel('Next step',{exact:true}).selectOption('Follow up');await nav('Save changes')
 await page.locator('.saved-lead').getByText('Follow up',{exact:true}).waitFor()
 const exported=page.waitForEvent('download');await nav('Export research notebook');const file=await exported
 await file.saveAs('../../test-results/research-notebook.json')
 assert.equal(JSON.parse(await readFile('../../test-results/research-notebook.json','utf8')).items[0].status,'Follow up')
 await page.screenshot({path:'../../test-results/search-assistant.png',fullPage:true,animations:'disabled'})
 await page.reload();await page.getByText('EXAMPLE DATA · FICTIONAL WEBSITE').waitFor();await nav('Google search assistant')
 await page.getByRole('heading',{name:'Example public report',exact:true}).waitFor()
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'../../test-results/search-assistant-mobile.png',fullPage:true,animations:'disabled'})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await nav('Remove lead');await page.getByText('No research saved yet.',{exact:false}).waitFor()
 await page.getByText('Advanced details',{exact:true}).click();await nav('Evidence review')
 await page.getByRole('heading',{name:'Observation → alternative explanation → conclusion'}).waitFor()
 await nav('Workspace guide');const backup=page.waitForEvent('download');await page.getByRole('link',{name:'Download workspace backup'}).click()
 assert.equal((await backup).suggestedFilename(),'netra-workspace-backup.sqlite3')
 assert.deepEqual(errors,[])
 console.log('PASS: guide, 18 evaluation fixtures, registration, 13 queries, persistent research editing/export/removal, mobile layout, evidence review, backup; no browser errors.')
} finally {await browser.close()}
