import {chromium} from '@playwright/test'
import {mkdir, readFile} from 'node:fs/promises'
import assert from 'node:assert/strict'

await mkdir('../../test-results',{recursive:true})
const browser = await chromium.launch({channel:'msedge',headless:true})
const page = await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
try {
  await page.goto('http://127.0.0.1:8001')
  await page.getByRole('button',{name:'Show me an example'}).click()
  await page.getByText('EXAMPLE DATA · FICTIONAL WEBSITE').waitFor()
  await page.getByRole('button',{name:'Present to an audience'}).waitFor()
  await page.screenshot({path:'../../test-results/website-checkup-desktop.png',fullPage:true})
  await page.getByRole('button',{name:'Show advisory checks'}).click()
  assert.equal(await page.locator('.plain-card').count(),1)
  await page.getByRole('button',{name:'Show checks needing attention'}).click()
  assert.equal(await page.locator('.plain-card').count(),4)
  await page.getByRole('button',{name:'Present to an audience'}).click()
  assert.equal(await page.locator('dialog').evaluate(e=>e.open),true)
  await page.getByRole('button',{name:'Next',exact:false}).click()
  await page.locator('dialog').press('ArrowRight')
  await page.screenshot({path:'../../test-results/presenter-mode.png'})
  await page.locator('dialog').press('Escape')
  assert.equal(await page.locator('dialog').evaluate(e=>e.open),false)
  const reportDownload = page.waitForEvent('download')
  await page.getByRole('link',{name:'Download audience handout'}).click()
  const report = await reportDownload
  await report.saveAs('../../test-results/audience-handout.html')
  assert.match(await readFile('../../test-results/audience-handout.html','utf8'), /Higher is better/)
  await page.getByRole('button',{name:'My action plan',exact:true}).click()
  await page.getByLabel('Owner for hsts').fill('Website team')
  await page.getByLabel('Progress for hsts').selectOption('In progress')
  await page.locator('form.action-item').filter({has:page.getByLabel('Owner for hsts')}).getByRole('button',{name:'Save action'}).click()
  await page.getByText('Saved to this checkup.').waitFor()
  await page.reload()
  await page.getByRole('button',{name:'My action plan',exact:true}).click()
  assert.equal(await page.getByLabel('Owner for hsts').inputValue(),'Website team')
  assert.equal(await page.getByLabel('Progress for hsts').inputValue(),'In progress')
  const planDownload = page.waitForEvent('download')
  await page.getByRole('button',{name:'Download action checklist'}).click()
  assert.equal((await planDownload).suggestedFilename(),'netra-action-plan.txt')
  await page.getByRole('button',{name:'Public information',exact:true}).click()
  assert.equal(await page.locator('.discovery-links article').count(),2)
  await page.getByRole('button',{name:'Website checkup',exact:true}).click()
  await page.getByRole('button',{name:'Create improved demo'}).click()
  await page.getByText('No scored gaps in the observed checks',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Compare results',exact:true}).click()
  const options = await page.getByLabel('Earlier checkup').locator('option').all()
  assert.ok(options.length > 1)
  await page.getByLabel('Earlier checkup').selectOption({index:1})
  await page.getByText('+45 points',{exact:true}).waitFor()
  await page.getByRole('button',{name:'Website checkup',exact:true}).click()
  await page.getByLabel('Find a technical term').fill('DNS')
  await page.locator('.glossary summary').first().click()
  await page.getByText('The internet directory that connects names to services.').waitFor()
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'../../test-results/website-checkup-mobile.png',fullPage:true})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false)
  await page.getByRole('button',{name:'Light view',exact:true}).click()
  await page.screenshot({path:'../../test-results/website-checkup-light-mobile.png',fullPage:true})
  await page.getByRole('button',{name:'Past checkups',exact:true}).click()
  await page.getByLabel('Find a past website checkup').fill('does-not-exist')
  await page.getByText('No saved checkups match that website.').waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS: readable checkup, state filters, presenter keyboard controls, handout, persistent action plan, text export, public links, improved demo, comparison, glossary, mobile layout, appearance, history search; no page errors.')
} finally {await browser.close()}
