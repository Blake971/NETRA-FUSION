import {chromium} from '@playwright/test'
import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
await mkdir('../../test-results',{recursive:true})
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1440,height:1000}})
const errors=[];page.on('pageerror',e=>errors.push(e.message))
const nav=name=>page.getByRole('button',{name,exact:true}).click()
try{
 await page.goto('http://127.0.0.1:8001')
 await nav('Google search assistant')
 assert.equal(await page.getByLabel('Search scope',{exact:true}).inputValue(),'google')
 await page.getByLabel('Research topic',{exact:true}).fill('renewable energy')
 await page.getByLabel('Research category',{exact:true}).selectOption('documents')
 await nav('Generate search queries')
 await page.getByRole('heading',{name:'Public documents',exact:true}).waitFor()
 const global=await page.locator('.plain-card code').innerText()
 assert.ok(global.includes('filetype:docx'));assert.ok(!global.includes('site:'))
 assert.ok((await page.getByRole('link',{name:'Open Google'}).getAttribute('href')).startsWith('https://www.google.com/search?'))
 await page.screenshot({path:'../../test-results/google-first-search.png',fullPage:true,animations:'disabled'})
 await page.getByLabel('Search scope',{exact:true}).selectOption('website')
 await page.getByLabel('Research website',{exact:true}).fill('example.com')
 await nav('Generate search queries')
 await page.getByRole('heading',{name:'Public documents',exact:true}).waitFor()
 assert.match(await page.locator('.plain-card code').innerText(),/site:example.com/)
 await page.getByLabel('Research category',{exact:true}).selectOption('social');await nav('Generate search queries')
 await page.getByRole('heading',{name:'Public social profiles',exact:true}).waitFor()
 const social=await page.locator('.plain-card code').innerText();assert.ok(social.includes('"example.com"'));assert.ok(!social.includes('site:example.com'))
 await nav('Email exposure');await nav('Show fictional breach example')
 await page.getByRole('heading',{name:'Fictional forum example',exact:true}).waitFor()
 await page.screenshot({path:'../../test-results/email-exposure.png',fullPage:true,animations:'disabled'})
 await page.getByLabel('Email address to check',{exact:true}).fill('not-sent@example.com')
 assert.equal(await page.getByRole('heading',{name:'Fictional forum example',exact:true}).count(),0)
 await nav('Clear email and results');assert.equal(await page.getByLabel('Email address to check',{exact:true}).inputValue(),'')
 await nav('Website checkup');await page.getByRole('button',{name:'Show me an example'}).click()
 await page.getByText('EXAMPLE DATA · FICTIONAL WEBSITE').waitFor()
 await nav('Hosting and ownership')
 await page.getByText('Example hosting network (fictional)',{exact:true}).waitFor()
 await page.getByText('Origin: not established',{exact:true}).waitFor()
 await page.screenshot({path:'../../test-results/hosting-attribution.png',fullPage:true,animations:'disabled'})
 await page.getByRole('button',{name:'Light view',exact:true}).click()
 await page.screenshot({path:'../../test-results/hosting-attribution-light.png',fullPage:true,animations:'disabled'})
 await page.setViewportSize({width:390,height:844})
 await page.screenshot({path:'../../test-results/hosting-attribution-mobile.png',fullPage:true,animations:'disabled'})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await nav('Email exposure');await nav('Show fictional breach example')
 await page.getByRole('heading',{name:'Fictional forum example',exact:true}).waitFor()
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.screenshot({path:'../../test-results/email-exposure-mobile.png',fullPage:true,animations:'disabled'})
 assert.deepEqual(errors,[])
 console.log('PASS: Google-first search without assessment, website scope, external social references, email demo and clear, hosting provenance, responsive light/dark layouts; no browser errors.')
}finally{await browser.close()}
